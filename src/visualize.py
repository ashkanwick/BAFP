"""
Reusable Persian visualisations for the BAFP capstone (no Jupyter needed).
=========================================================================

Why this module exists separately
---------------------------------
The original plan had the EDA in ``notebooks/EDA.ipynb``. ``jupyter`` cannot be
installed on this machine: the jupyterlab install aborted with

    OSError: [Errno 2] No such file or directory: ...\\jupyterlab\\galata\\...\\....js

because Windows long-path support is disabled (see install.log). So the EDA
deliverable is generated by a plain script instead:

    python -m src.visualize                     # writes assets/figures/*.png
    python -m src.visualize --csv data/cleaned_comments_wide.csv --prefix wide

Every figure is both saved as a PNG (for the report/slides) and importable as a
function, so ``app.py`` reuses the same font and word-frequency code rather than
keeping a second copy of it.

The Persian rendering problem this solves
----------------------------------------
Two text stacks are in play and they need OPPOSITE handling. Both facts were
measured here, not assumed (see ``assets/figures/_shape_test.png`` for the
comparison that settled it):

  * **matplotlib** (3.11, this install) already reshapes and bidi-reorders
    Arabic/Persian. Give it raw logical-order text plus a Persian font and it is
    correct. Give it *pre-shaped* text and it re-processes the presentation
    forms, which renders reversed, disconnected glyphs. So matplotlib figures
    must never be pre-shaped -- :func:`configure_matplotlib` only registers the
    font and points ``font.family`` at it.
  * **Pillow** -- used by ``wordcloud`` -- reports
    ``PIL.features.check('raqm')`` as **False** on this build, so it draws
    isolated left-to-right glyphs. There :func:`shape_for_pillow` applies
    arabic_reshaper + python-bidi per word, which is what makes the word clouds
    readable.

:func:`shaping_needed` reports whether the Pillow branch is active.

The font itself is a real dependency: no Persian TTF ships with this Windows
install, so :func:`ensure_font` resolves a cached Vazirmatn, else downloads it
into ``assets/fonts/``, else falls back to ``C:/Windows/Fonts/tahoma.ttf``.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Iterable, Sequence

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_ROOT / "data"
FONTS_DIR = PROJECT_ROOT / "assets" / "fonts"
FIGURES_DIR = PROJECT_ROOT / "assets" / "figures"

VAZIRMATN_URLS: tuple[str, ...] = (
    "https://raw.githubusercontent.com/rastikerdar/vazirmatn/master/fonts/ttf/Vazirmatn-Regular.ttf",
    "https://github.com/rastikerdar/vazirmatn/raw/master/fonts/ttf/Vazirmatn-Regular.ttf",
)
WINDOWS_FALLBACKS: tuple[Path, ...] = (
    Path("C:/Windows/Fonts/tahoma.ttf"),
    Path("C:/Windows/Fonts/tahomabd.ttf"),
    Path("C:/Windows/Fonts/arala.ttf"),
)

LABEL_ORDER = ["negative", "neutral", "positive"]
LABEL_COLORS = {"negative": "#E4572E", "neutral": "#F3A712", "positive": "#2AA198"}
LABEL_FA = {"negative": "منفی", "neutral": "خنثی", "positive": "مثبت"}

LOG = logging.getLogger("bafp.visualize")

__all__ = [
    "LABEL_COLORS", "LABEL_FA", "LABEL_ORDER",
    "build_wordcloud_image", "ensure_font", "top_words", "word_cloud_text",
    "shape_for_pillow", "shaping_needed", "configure_matplotlib",
    "generate_report", "summary_table", "word_frequency_table",
]

_FONT_CACHE: dict[str, Any] = {}


# ==========================================================================
# Font + shaping layer (also used by app.py)
# ==========================================================================
def ensure_font(force: bool = False) -> tuple[str | None, str]:
    """Return ``(font_path, note)`` for a Persian-capable TTF.

    Checks the cache dir first, then tries the network, then falls back to a
    Windows font. Returns ``(None, note)`` only if nothing at all is available.
    """
    cached = _FONT_CACHE.get("path")
    if cached and not force:
        return cached[0], cached[1]

    FONTS_DIR.mkdir(parents=True, exist_ok=True)
    local = sorted(FONTS_DIR.glob("Vazirmatn*.ttf"))
    if local and not force:
        result = (str(local[0]), f"using cached font {local[0].name}")
        _FONT_CACHE["path"] = result
        return result

    try:
        import requests

        for url in VAZIRMATN_URLS:
            try:
                response = requests.get(url, timeout=25)
            except Exception:  # noqa: BLE001 - next URL / the fallback
                continue
            if response.status_code == 200 and len(response.content) > 100_000:
                dest = FONTS_DIR / "Vazirmatn-Regular.ttf"
                dest.write_bytes(response.content)
                result = (str(dest), f"downloaded Vazirmatn ({len(response.content) / 1e6:.1f} MB)")
                _FONT_CACHE["path"] = result
                return result
    except ImportError:  # pragma: no cover - requests is a declared dependency
        pass

    for candidate in WINDOWS_FALLBACKS:
        if candidate.exists():
            result = (str(candidate), f"Vazirmatn unreachable; using {candidate.name}")
            _FONT_CACHE["path"] = result
            return result
    return None, "No Persian-capable font found; Persian labels will not render."


def shaping_needed() -> bool:
    """True when Pillow lacks raqm, so Arabic/Persian text must be pre-shaped.

    Applies to the Pillow/wordcloud path ONLY -- matplotlib shapes RTL itself
    and double-shaping it produces reversed, disconnected glyphs.
    """
    try:
        from PIL import features

        return not features.check("raqm")
    except Exception:  # noqa: BLE001 - conservative: pre-shape
        return True


def shape_for_pillow(text: str) -> str:
    """Reshape + bidi-reorder for Pillow, which has no raqm on this build.

    Call this per WORD, not per sentence: the cloud lays words out itself, and
    bidi reordering across spaces would move words to the wrong side.
    """
    if not shaping_needed():
        return text
    try:
        import arabic_reshaper
        from bidi.algorithm import get_display

        return get_display(arabic_reshaper.reshape(text))
    except ImportError:
        return text


def configure_matplotlib() -> str | None:
    """Point matplotlib's default font at a Persian TTF. Returns the font name.

    No shaping happens here on purpose: this matplotlib build already applies
    Arabic/Persian joining and bidi reordering to raw text.
    """
    import matplotlib

    matplotlib.use("Agg")  # headless: this runs during training and in CI alike
    from matplotlib import font_manager

    path, note = ensure_font()
    if not path:
        LOG.warning("matplotlib will fall back to DejaVu: %s", note)
        return None
    font_manager.fontManager.addfont(path)
    name = font_manager.FontProperties(fname=path).get_name()
    matplotlib.rcParams["font.family"] = name
    matplotlib.rcParams["axes.unicode_minus"] = False
    return name


# ==========================================================================
# Text statistics
# ==========================================================================
def top_words(texts: Iterable[str], limit: int = 30, min_len: int = 3) -> Counter[str]:
    """Count words longer than ``min_len``, keeping only the ``limit`` most common.

    The truncation matters: a Counter raises nothing on ``counter[slice]``, it
    returns 0, so callers that forget ``most_common`` get a silent empty plot.
    """
    counter: Counter[str] = Counter()
    for row in texts:
        counter.update(word for word in str(row).split() if len(word) > min_len)
    return Counter(dict(counter.most_common(limit)))


def word_cloud_text(words: Counter[str]) -> str:
    """Expand a word->count Counter back into the repeated-token string WordCloud counts.

    ``WordCloud`` sizes a glyph by how often it appears in its input, so passing
    each word once would draw rank order rather than frequency.
    """
    return " ".join(word for word, count in words.items() for _ in range(int(count)))


def word_frequency_table(
    frame: pd.DataFrame, text_column: str = "eda_text", limit: int = 40
) -> pd.DataFrame:
    """Long-format per-label word counts -- the CSV a report table is built from."""
    rows: list[dict[str, Any]] = []
    groups: list[tuple[str, pd.DataFrame]] = [
        ("all", frame)
    ] + [
        (label, frame[frame["label_name"] == label])
        for label in LABEL_ORDER
        if "label_name" in frame.columns
    ]
    for name, subset in groups:
        if subset.empty:
            continue
        for rank, (word, count) in enumerate(
            top_words(subset[text_column].fillna(""), limit=limit).most_common(limit), start=1
        ):
            rows.append({"group": name, "rank": rank, "word": word, "count": int(count)})
    return pd.DataFrame(rows)


def summary_table(frame: pd.DataFrame) -> pd.DataFrame:
    """Per-label row counts, means and share -- printed and saved as CSV."""
    rows: list[dict[str, Any]] = []
    total = len(frame)
    groups = [("all", frame)]
    if "label_name" in frame.columns:
        groups += [(label, frame[frame["label_name"] == label]) for label in LABEL_ORDER]
    for name, subset in groups:
        if subset.empty:
            continue
        lengths = pd.to_numeric(subset.get("n_tokens"), errors="coerce")
        rows.append(
            {
                "group": name,
                "rows": int(len(subset)),
                "share_pct": round(100 * len(subset) / max(total, 1), 2),
                "mean_tokens": round(float(lengths.mean()), 2) if lengths.notna().any() else None,
                "median_tokens": float(lengths.median()) if lengths.notna().any() else None,
                "p95_tokens": float(lengths.quantile(0.95)) if lengths.notna().any() else None,
            }
        )
    return pd.DataFrame(rows)


