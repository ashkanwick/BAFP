def _save(figure: Any, path: Path, close: bool = True) -> Path:
    configure_matplotlib()  # rcParams are read at draw time, so this is enough
    figure.tight_layout()
    figure.savefig(path, dpi=150, bbox_inches="tight")
    if close:
        import matplotlib.pyplot as plt

        plt.close(figure)
    LOG.info("wrote %s", path)
    return path


def plot_label_distribution(frame: pd.DataFrame, path: Path) -> Path | None:
    if "label_name" not in frame.columns or frame["label_name"].notna().sum() == 0:
        return None
    import matplotlib.pyplot as plt

    counts = frame["label_name"].value_counts().reindex(LABEL_ORDER).fillna(0)
    figure, ax = plt.subplots(figsize=(6, 3.6))
    ax.barh(
        [LABEL_FA[name] for name in counts.index],
        counts.values,
        color=[LABEL_COLORS[name] for name in counts.index],
    )
    for index, value in enumerate(counts.values):
        ax.text(value, index, f" {int(value)}", va="center")
    ax.set_title("توزیع برچسب‌ها")
    ax.set_xlabel("تعداد نظر")
    return _save(figure, path)


def plot_top_words(frame: pd.DataFrame, path: Path, limit: int = 20,
                   text_column: str = "eda_text") -> Path | None:
    import matplotlib.pyplot as plt

    words = top_words(frame[text_column].fillna("").astype(str), limit=limit).most_common()[::-1]
    if not words:
        return None
    labels, counts = zip(*words)
    figure, ax = plt.subplots(figsize=(6.5, 6))
    ax.barh(list(labels), list(counts), color="#2E5A86")
    ax.set_title("پرکاربردترین واژه‌ها")
    ax.tick_params(axis="y", labelsize=9)
    return _save(figure, path)


def plot_length_distribution(frame: pd.DataFrame, path: Path) -> Path | None:
    if "n_tokens" not in frame.columns:
        return None
    import matplotlib.pyplot as plt

    lengths = pd.to_numeric(frame["n_tokens"], errors="coerce").dropna()
    if lengths.empty:
        return None
    figure, ax = plt.subplots(figsize=(6.5, 3.6))
    ax.hist(lengths, bins=45, color="#6B7A99")
    ax.axvline(lengths.median(), color="#E4572E", linestyle="--", label="median")
    ax.set_title("توزیع طول نظرات (واژگانه)")
    ax.set_xlabel("تعداد واژگان")
    ax.legend()
    return _save(figure, path)


def plot_per_class_metrics(metrics: dict[str, Any], path: Path) -> Path | None:
    import matplotlib.pyplot as plt

    test = metrics.get("test") or metrics.get("best_val") or {}
    per_class = test.get("per_class") or {}
    if not per_class:
        return None
    figure, ax = plt.subplots(figsize=(6.5, 3.8))
    labels = [label for label in LABEL_ORDER if label in per_class]
    width = 0.26
    positions = range(len(labels))
    for offset, metric in zip((-width, 0.0, width), ("precision", "recall", "f1-score")):
        ax.bar(
            [position + offset for position in positions],
            [per_class[label][metric] for label in labels],
            width,
            label=metric,
        )
    ax.set_xticks(list(positions))
    ax.set_xticklabels([LABEL_FA[label] for label in labels])
    ax.set_ylim(0, 1.05)
    ax.set_title("دقت، یادآوری و F1 به تفکیک کلاس (آزمون)")
    ax.legend()
    return _save(figure, path)


def plot_confusion_matrix(metrics: dict[str, Any], path: Path) -> Path | None:
    import matplotlib.pyplot as plt

    test = metrics.get("test") or metrics.get("best_val") or {}
    matrix = test.get("confusion_matrix")
    if not matrix:
        return None
    labels = test.get("labels", LABEL_ORDER)
    figure, ax = plt.subplots(figsize=(5.2, 4.4))
    image = ax.imshow(matrix, cmap="Blues")
    ax.set_xticks(range(len(labels)))
    ax.set_yticks(range(len(labels)))
    names = [LABEL_FA.get(label, label) for label in labels]
    ax.set_xticklabels(names)
    ax.set_yticklabels(names)
    size = max(max(row) for row in matrix) or 1
    for row_index, row in enumerate(matrix):
        for column_index, value in enumerate(row):
            ax.text(column_index, row_index, str(value), ha="center", va="center",
                    color="white" if value > size / 2 else "#1a1a1a")
    ax.set_xlabel("پیش‌بینی")
    ax.set_ylabel("واقعیت")
    ax.set_title("ماتریس خطا (آزمون)")
    figure.colorbar(image, ax=ax, shrink=0.8)
    return _save(figure, path)


def build_wordcloud_image(text: str, font_path: str | None = None) -> Any:
    """Word cloud as a PIL image, or None when it cannot be rendered.

    ``WordCloud.generate()`` returns the WordCloud object; callers need
    ``to_image()`` for anything that consumes an image.
    """
    font_path = font_path or ensure_font()[0]
    if not font_path or not text.strip():
        return None
    from wordcloud import STOPWORDS, WordCloud

    body = " ".join(shape_for_pillow(word) for word in text.split())
    cloud = WordCloud(
        font_path=font_path,
        width=900,
        height=460,
        background_color="white",
        max_words=140,
        relative_scaling=0.45,
        stopwords=set(STOPWORDS),
        prefer_horizontal=0.95,
    )
    cloud.generate(body)
    return cloud.to_image()


def plot_per_class_wordclouds(frame: pd.DataFrame, figures_dir: Path,
                              text_column: str = "eda_text", limit: int = 200,
                              prefix: str = "") -> list[Path]:
    """One word cloud per label, so the scarce class is inspected separately."""
    font_path, note = ensure_font()
    if not font_path:
        LOG.warning("skipping word clouds: %s", note)
        return []
    stem = f"{prefix}_" if prefix else ""
    written: list[Path] = []
    for label in LABEL_ORDER:
        subset = frame[frame["label_name"] == label] if "label_name" in frame.columns else frame
        if subset.empty:
            continue
        words = word_cloud_text(
            top_words(subset[text_column].fillna("").astype(str), limit=limit))
        image = build_wordcloud_image(words, font_path)
        if image is None:
            continue
        path = figures_dir / f"{stem}wordcloud_{label}.png"
        image.save(path)
        LOG.info("wrote %s", path)
        written.append(path)
    return written


# ==========================================================================
# Report driver
# ==========================================================================
def generate_report(
    csv_path: Path,
    figures_dir: Path = FIGURES_DIR,
    metrics_path: Path | None = None,
    prefix: str = "",
) -> dict[str, Any]:
    """Write every figure + CSV table for one cleaned corpus. Returns a manifest."""
    font_name = configure_matplotlib()

    if not csv_path.exists():
        raise FileNotFoundError(f"{csv_path} not found; run src/preprocess.py first")
    frame = pd.read_csv(csv_path, encoding="utf-8-sig")
    figures_dir.mkdir(parents=True, exist_ok=True)
    stem = f"{prefix}_" if prefix else ""
    text_column = "eda_text" if "eda_text" in frame.columns else "clean_text"

    written: list[str] = []

    def add(path: Path | None) -> None:
        if path:
            written.append(path.name)

    add(plot_label_distribution(frame, figures_dir / f"{stem}label_distribution.png"))
    add(plot_top_words(frame, figures_dir / f"{stem}top_words.png", text_column=text_column))
    add(plot_length_distribution(frame, figures_dir / f"{stem}length_distribution.png"))
    written.extend(path.name for path in plot_per_class_wordclouds(
        frame, figures_dir, text_column, prefix=prefix))

    summary = summary_table(frame)
    summary_path = figures_dir / f"{stem}summary_table.csv"
    summary.to_csv(summary_path, index=False, encoding="utf-8-sig")
    written.append(summary_path.name)

    frequencies = word_frequency_table(frame, text_column=text_column)
    frequency_path = figures_dir / f"{stem}word_frequencies.csv"
    frequencies.to_csv(frequency_path, index=False, encoding="utf-8-sig")
    written.append(frequency_path.name)

    metrics: dict[str, Any] | None = None
    metrics_source: str | None = None
    candidates: list[Path] = []
    if metrics_path:
        candidates.append(metrics_path)
    checkpoints = [
        PROJECT_ROOT / "models" / "parsbert-sentiment-3class",
        PROJECT_ROOT / "models" / "parsbert-sentiment-3class-wide",
    ]
    # Pair each report with the checkpoint trained on its own corpus; without
    # this the base metrics.json always wins and lands in wide-prefixed files.
    checkpoints.sort(key=lambda d: ("wide" in d.name) != ("wide" in stem))
    candidates.extend(directory / "metrics.json" for directory in checkpoints)
    for candidate in candidates:
        if not candidate.exists():
            continue
        try:
            metrics = json.loads(candidate.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError) as exc:
            LOG.warning("could not read %s: %s", candidate, exc)
            continue
        add(plot_per_class_metrics(
            metrics, figures_dir / f"{stem}per_class_metrics.png"))
        add(plot_confusion_matrix(
            metrics, figures_dir / f"{stem}confusion_matrix.png"))
        metrics_source = str(candidate)
        break

    if metrics is None:
        LOG.info("no metrics.json found yet; model figures will be written after training")

    manifest = {
        "csv": str(csv_path),
        "rows": int(len(frame)),
        "products": int(frame["product_id"].nunique()) if "product_id" in frame else None,
        "font": ensure_font()[0],
        "matplotlib_font": font_name,
        "pillow_raqm_available": not shaping_needed(),
        "metrics": metrics_source,
        "figures": sorted(set(written)),
        "labels": summary.to_dict("records"),
    }
    (figures_dir / f"{stem}manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return manifest


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--csv", type=Path, default=DATA_DIR / "cleaned_comments.csv")
    parser.add_argument("--out", type=Path, default=FIGURES_DIR)
    parser.add_argument("--metrics", type=Path, default=None)
    parser.add_argument("--prefix", type=str, default="",
                        help="filename prefix, e.g. 'wide' for the wide corpus figures")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)-7s %(message)s",
        datefmt="%H:%M:%S",
    )

    try:
        manifest = generate_report(args.csv, args.out, args.metrics, args.prefix)
    except FileNotFoundError as exc:
        print(str(exc))
        return 1

    print("\n" + "=" * 62)
    print("EDA report written")
    print("=" * 62)
    print(f"  corpus            : {manifest['csv']} ({manifest['rows']} rows, "
          f"{manifest['products']} products)")
    print(f"  font              : {manifest['font']}")
    print(f"  matplotlib font   : {manifest['matplotlib_font']} "
          f"(matplotlib shapes Persian itself; text is passed raw)")
    print(f"  pillow raqm       : {manifest['pillow_raqm_available']} "
          f"(False = word clouds pre-shaped with arabic-reshaper + bidi)")
    print(f"  metrics           : {manifest['metrics'] or 'none yet'}")
    print(f"  figures           : {args.out}")
    for name in manifest["figures"]:
        print(f"    - {name}")
    print("\n  summary:")
    print(summary_table(pd.read_csv(args.csv, encoding="utf-8-sig")).to_string(index=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
